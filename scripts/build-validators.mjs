// Compiles the bundled official JSON Schemas into plain ES module code at build time.
// Why: the hosted site sends `script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval'`
// (no 'unsafe-eval'). Ajv's runtime compile uses `new Function`, which that CSP blocks,
// and that blocked call left the published page blank. Generated validators need no eval.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv/dist/compile/codegen/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schema = (name) => JSON.parse(readFileSync(resolve(root, "src/schemas", `${name}.json`), "utf8"));
const ajv = new (Ajv2020.default ?? Ajv2020)({
  strict: false,
  allErrors: false,
  inlineRefs: false,
  code: { source: true, esm: true, formats: _`require("./formats").formats` },
});
(addFormats.default ?? addFormats)(ajv);
const uint = { type: "string", validate: () => true }; // compile-time placeholder; runtime uses ./formats
for (const bits of [64, 96, 256]) ajv.addFormat(`uint${bits}-decimal`, uint);
ajv.addSchema(schema("status"), "status");
ajv.addSchema(schema("settlements"), "history");
ajv.addSchema(schema("events"), "events");
let code = (standaloneCode.default ?? standaloneCode)(ajv, { status: "status", history: "history", events: "events" });

// Ajv calls require("ajv/dist/runtime/ucs2length").default. Node's namespace
// wraps that CommonJS export twice, while Vite exposes the function directly.
// Normalize to a callable once, and replace the entire generated member access
// before converting the remaining requires. Unwrapping both here and at the call
// site makes every valid production response throw despite passing in Node.
const lengthRuntime = "ajv/dist/runtime/ucs2length";
if (!code.includes(`require("${lengthRuntime}").default`))
  throw new Error("Ajv's string-length runtime changed; review the generated import.");
code = code.replaceAll(`require("${lengthRuntime}").default`, "__ucs2length");
const runtimeImport = `import * as __ucs2length_ns from "${lengthRuntime}.js";
let __ucs2length = __ucs2length_ns;
while (typeof __ucs2length !== "function" && __ucs2length?.default)
  __ucs2length = __ucs2length.default;
if (typeof __ucs2length !== "function") throw new TypeError("Invalid Ajv string-length runtime");`;

// Turn every remaining CommonJS require() into a static ES import.
const modules = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_m, spec) => {
  if (!modules.has(spec)) modules.set(spec, `__req${modules.size}`);
  return modules.get(spec);
});
const imports = [...modules].map(([spec, id]) => {
  const target = spec.startsWith("ajv/") && !spec.endsWith(".js") ? `${spec}.js` : spec;
  if (spec.startsWith(".")) return `import * as ${id} from "${target}";`;
  return `import * as ${id}_ns from "${target}";\nconst ${id} = ${id}_ns.default ?? ${id}_ns;`;
});
if (/\b(eval|new Function)\b/.test(code)) throw new Error("Generated validators must not evaluate strings.");
const header = "/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/build-validators.mjs from src/schemas/*.json. Do not edit.\n";
writeFileSync(resolve(root, "src/validation/validators.js"), header + runtimeImport + "\n" + imports.join("\n") + "\n" + code);
console.log(`validators: ${code.length} bytes, imports: ${[...modules.keys()].join(", ")}`);
